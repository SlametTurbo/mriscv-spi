/* Uji multiplier hardware (MULT.v) -- 2026-09-28.
 * mul/mulh/mulhsu/mulhu dipanggil lewat inline asm dengan ".option arch, +m",
 * sehingga SISA program tetap rv32i murni (compiler tidak memakai mul untuk
 * indexing dsb. -- kalau MULT rusak, harness uji ini tetap benar).
 * Nilai harapan dihitung di host (Python), bukan di firmware.
 * Output UART (115200): satu baris per vektor yang GAGAL, lalu ringkasan
 *   "MUL TEST: <lulus>/<total> operasi LULUS" (hex). LED = jumlah vektor gagal. */
#define M_OP(op, a, b) ({ unsigned _r; __asm__ volatile( \
    ".option push\n.option arch, +m\n" op " %0, %1, %2\n.option pop" \
    : "=r"(_r) : "r"(a), "r"(b)); _r; })

