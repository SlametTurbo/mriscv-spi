#define NVEC (sizeof(vec)/sizeof(vec[0]))

static void put_hex(unsigned v){
    for (int i = 28; i >= 0; i -= 4) {
        unsigned d = (v >> i) & 0xFu;
        uart_putc((char)(d < 10u ? '0' + d : 'A' + d - 10u));
    }
}

static void report(const char *op, unsigned i, unsigned got, unsigned exp){
    uart_puts("FAIL "); uart_puts(op); uart_puts(" vec#"); put_hex(i);
    uart_puts(" a="); put_hex(vec[i][0]); uart_puts(" b="); put_hex(vec[i][1]);
    uart_puts(" got="); put_hex(got); uart_puts(" exp="); put_hex(exp);
    uart_puts("\r\n");
}

int main(void) {
    for (;;) {
        unsigned pass = 0, badvec = 0;
        for (unsigned i = 0; i < NVEC; i++) {
            unsigned a = vec[i][0], b = vec[i][1], r;
            unsigned ok = 1;
            r = M_OP("mul",    a, b); if (r == vec[i][2]) pass++; else { report("mul   ", i, r, vec[i][2]); ok = 0; }
            r = M_OP("mulh",   a, b); if (r == vec[i][3]) pass++; else { report("mulh  ", i, r, vec[i][3]); ok = 0; }
            r = M_OP("mulhsu", a, b); if (r == vec[i][4]) pass++; else { report("mulhsu", i, r, vec[i][4]); ok = 0; }
            r = M_OP("mulhu",  a, b); if (r == vec[i][5]) pass++; else { report("mulhu ", i, r, vec[i][5]); ok = 0; }
            if (!ok) badvec++;
        }
        uart_puts("MUL TEST: "); put_hex(pass); uart_putc('/'); put_hex(NVEC * 4u);
        uart_puts(" operasi LULUS\r\n");
        led_set(badvec);
        delay(0x400000);
    }
}
